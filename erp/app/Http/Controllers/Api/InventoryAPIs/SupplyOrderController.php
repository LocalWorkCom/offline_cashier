    public function update(Request $request, $id)
    {
        $lang = $request->header('lang', 'ar');
        $validator = Validator::make($request->all(), [
            'from_store_id' => 'required|exists:stores,id',
            'to_store_id'   => 'required|exists:stores,id|different:from_store_id',
            'employee_id'   => 'required|exists:employees,id|',
            'supply_reason_id'  => 'required|exists:supply_order_reasons,id',
            'status'            => 'sometimes|in:draft,submitted',
            'type'              => 'required|in:one-time,periodic',
            'items'             => 'required|array|min:1',
            'items.*.product_brand_id'      => 'required|exists:product_brands,id',
            'items.*.quantity'  => 'required|numeric|min:1',
            'items.*.unit_id'      => 'required|exists:units,id',
            'items.*.notes'     => 'nullable|string',
        ]);
        if ($validator->fails()) {
            $message = $lang == 'en' ? 'Validation Error.' : 'خطأ في التحقق من الصحة.';
            return respondError($message, 400, $validator->errors());
        }

        $supplyOrder = SupplyOrder::find($id);
        if (!$supplyOrder) {
            $message = $lang == 'en' ? 'Supply order not found.' : 'لم يتم العثور على طلب التوريد.';
            return respondError($message, 404);
        }
        if ($supplyOrder->status !== 'draft') {
            $message =  $lang == 'en' ? "Only draft orders can be updated." : 'فقط يمكن تحديث الطلبات في حالة المسودة.';
            return respondErrorData($message, 400,  []);
        }
        $supplyOrder = $this->supplyOrderService->update($supplyOrder, $request->all());
        return ResponseWithSuccessData($lang, $supplyOrder->load('items'), 1);
    }

    public function submit(Request $request, $id)
    {
        $lang = $request->header('lang', 'ar');

        $supplyOrder = SupplyOrder::find($id);
        if (!$supplyOrder) {
            $message = $lang == 'en' ? 'Supply order not found.' : 'لم يتم العثور على طلب التوريد.';
            return respondError($message, 404, []);
        }
        if ($supplyOrder->status !== 'draft') {
            $message = $lang == 'en'
                ? "Only draft orders can be updated."
                : 'فقط يمكن تحديث الطلبات في حالة المسودة.';
            return respondErrorData($message, 400, []);
        }

        $this->supplyOrderService->submitSupplyOrder($supplyOrder);
        $supplyOrder->refresh();
        return ResponseWithSuccessData($lang, $supplyOrder, 1);
    }


    public function approve(Request $request, $id)
    {
        $lang = $request->header('lang', 'ar');
        $supplyOrder = SupplyOrder::find($id);
        if (!$supplyOrder) {
            $message = $lang == 'en' ? 'Supply order not found.' : 'لم يتم العثور على طلب التوريد.';
            return respondError($message, 404);
        }

        $supplyOrder =  $this->supplyOrderService->approve($supplyOrder);
        if (is_array($supplyOrder) && isset($supplyOrder['error'])) {
            $message = $lang == 'en' ? $supplyOrder['message_en'] : $supplyOrder['message_ar'];
            return respondError($message, $supplyOrder['code']);
        }
        return ResponseWithSuccessData($lang, $supplyOrder, 1);
    }


    public function reject(Request $request, $id)
    {
        $lang = $request->header('lang', 'ar');

        $validator = Validator::make($request->all(), [
            'reject_reason_id' => 'required|exists:supply_order_reject_reasons,id',
            'rejection_note' => 'nullable|string|max:1000',
        ]);
        if ($validator->fails()) {
            $message = $lang == 'en' ? 'Validation Error.' : 'خطأ في التحقق من الصحة.';
            return respondError($message, 400, $validator->errors());
        }
        $supplyOrder = SupplyOrder::find($id);
        if (!$supplyOrder) {
            $message = $lang == 'en' ? 'Supply order not found.' : 'لم يتم العثور على طلب التوريد.';
            return respondError($message, 404, []);
        }
      $result=  $this->supplyOrderService->reject($supplyOrder, $request->reject_reason_id, $request->rejection_note);
        if (is_array($result) && isset($result['error'])) {
            $message = $lang == 'en' ? $result['message_en'] : $result['message_ar'];
            return respondError($message, $result['code']);
        }
        $supplyOrder->refresh();
        return ResponseWithSuccessData($lang, $supplyOrder, 1);
    }
    public function destroy(Request $request, $id)
    {
        $lang = $request->header('lang', 'ar');

        $supplyOrder = SupplyOrder::find($id);
        if (!$supplyOrder) {
            $message = $lang == 'en' ? 'Supply order not found.' : 'لم يتم العثور على طلب التوريد.';
            return respondError($message, 404, []);
        }
        if ($supplyOrder->status != 'draft') {
            $message = $lang == 'en' ? 'Supply order cannot be deleted in draft status.' : 'لا يمكن حذف طلب التوريد في حالة المسودة.';
            return respondError($message, 400, []);
        }
        $this->supplyOrderService->destroy($supplyOrder);
        return ResponseWithSuccessData($lang, null, 1);
    }
}
