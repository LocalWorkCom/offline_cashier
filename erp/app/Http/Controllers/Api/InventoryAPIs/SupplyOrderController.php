    public function index(Request $request)
    {
        $lang = $request->header('lang', 'ar');

        $data = SupplyOrder::with(['fromStore', 'toStore', 'reason', 'items', 'items.productBrand', 'items.productBrand.product']);
        if ($request->has('status')) {
            $data->where('status', $request->status);
        }
        $orders = paginateOrGetAll($data, $request, [], []);
        $data = SupplyOrderResource::collection($orders['data']);
        return ResponseWithSuccessDataPaginated($lang, [
            'data' => $data,
            'meta' => $orders['meta'] ?? null,
        ], 1);
    }
    public function show(Request $request, $id)
    {
        $lang = $request->header('lang', 'ar');

        $order = SupplyOrder::with(['fromStore', 'toStore', 'reason', 'items', 'items.productBrand', 'items.productBrand.product'])->find($id);
        if (!$order) {
            $message = $lang == 'en'
                ? 'Supply order not found.'
                : 'لم يتم العثور على طلب التوريد.';
            return respondError($message, 404);
        }
        $data = new SupplyOrderResource($order);

        return ResponseWithSuccessData($lang, $data, 1);
    }
    public function createAutoGeneratedNumber(Request $request)
    {
        $lang = $request->header('lang', 'ar');
        $employee = auth('employee')->user();
        $soNumber = 'SO-' . now()->format('Ymd') . '-' . str_pad(SupplyOrder::count() + 1, 4, '0', STR_PAD_LEFT);

        $canUpdateNumber = $employee && $employee->can('update SupplyOrderNumber');
        return ResponseWithSuccessData(
            $lang == 'en' ? 'Auto generated supply order number.' : 'تم إنشاء رقم طلب التوريد تلقائيًا.',
            [
                'supply_order_number' => $soNumber,
                'can_update_number' => $canUpdateNumber,
            ],
            1
        );
    }


    public function store(Request $request)
    {
        $lang = $request->header('lang', 'ar');
        $employee = auth('employee')->user();

        $canUpdateNumber = $employee && $employee->can('update SupplyOrderNumber');

        $rules = [
            'from_store_id' => 'required|exists:stores,id',
            'to_store_id'   => 'required|exists:stores,id|different:from_store_id',
            'employee_id'   => 'required|exists:employees,id',
            'supply_reason_id' => 'required|exists:supply_order_reasons,id',
            'status'        => 'sometimes|in:draft,submitted',
            'type'          => 'required|in:one-time,periodic',
            'items'         => 'required|array|min:1',
            'items.*.product_brand_id' => 'required|exists:product_brands,id',
            'items.*.quantity'         => 'required|numeric|min:1',
            'items.*.unit_id'          => 'required|exists:units,id',
            'items.*.notes'            => 'nullable|string',
        ];

        // Add so_number rule dynamically based on permission
        if ($canUpdateNumber) {
            $rules['so_number'] = 'required|unique:supply_orders,order_number';
        } else {
            $rules['so_number'] = 'nullable|string'; // ignore uniqueness if no permission
        }

        $validator = Validator::make($request->all(), $rules);

        if ($validator->fails()) {
            $message = $lang == 'en' ? 'Validation Error.' : 'خطأ في التحقق من الصحة.';
            return respondError($message, 400, $validator->errors());
        }
        $data = $request->all();

        // If user cannot update number OR sent duplicate number → generate a new one
        if (!$canUpdateNumber) {
            if (!empty($data['so_number'])) {
                $exists = SupplyOrder::where('order_number', $data['so_number'])->exists();
                if ($exists) {
                    $data['so_number'] = null;
                }
            }
        }

        // Generate order number if missing or null
        if (empty($data['so_number'])) {
            $data['order_number'] = 'SO-' . now()->format('Ymd') . '-' . str_pad(SupplyOrder::count() + 1, 4, '0', STR_PAD_LEFT);
        } else {
            $data['order_number'] = $data['so_number'];
        }
        $supplyOrder = $this->supplyOrderService->createSupplyOrder($request->all());

        return ResponseWithSuccessData($lang, $supplyOrder, 1);
    }
