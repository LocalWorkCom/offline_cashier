    public function createAutoGeneratedNumber(Request $request)
    {
        $lang = $request->header('lang', 'ar');
        $employee = auth('employee')->user();

        // Call service
        $prNumber = $this->purchaseRequestService->generateAutoNumber();

        // Permission
        $canUpdateNumber = $employee && $employee->can('update PurchaseRequestNumber');

        return ResponseWithSuccessData(
            $lang === 'en'
                ? 'Auto generated purchase request number.'
                : 'تم إنشاء رقم طلب الشراء تلقائيًا.',
            [
                'purchase_request_number' => $prNumber,
                'can_update_number' => $canUpdateNumber,
            ],
            1
        );
    }

