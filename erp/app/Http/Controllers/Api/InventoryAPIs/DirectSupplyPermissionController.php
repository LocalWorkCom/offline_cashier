    public function updateStatus(Request $request, $id)
    {
        $lang = $request->header('lang', 'ar');
        try {
            $dsp = DirectSupplyPermission::findOrFail($id);

            $validated = Validator::make($request->all(), [
                'dsp_status' => 'required|exists:direct_supply_permission_status_settings,id',
            ]);
            if ($validated->fails()) {

                return respondError(($lang == 'en' ? 'Validation Error.' : 'خطأ في التحقق.'), 400, $validated->errors());
            }
            $dsp_status = DirectSupplyPermissionStatusSetting::find($dsp->dsp_status_id);
            if (!$dsp_status) {
                return respondError(
                    $lang == 'en' ? 'DSP status not found.' : 'حالة أمر الشراء غير موجودة.',
                    404
                );
            }
            $dsp_previous = $dsp_status->previous_statuses;
            $dsp_next = $dsp_status->next_statuses;

            if ($request->dsp_status == $dsp->dsp_status_id) {
                return respondError(
                    $lang == 'en' ? 'Same status.' : 'نفس الحالة.',
                    400
                );
            }
            if ($dsp_previous != null && in_array($request->dsp_status, $dsp_previous)) {
                return respondError(
                    $lang == 'en' ? 'Not allowed to transition to a previous status.' : 'غير مسموح للانتقال لحاله سابقه للحاله الحاليه',
                    400
                );
            }
            if ($dsp_status->type == 'final' || !in_array($request->dsp_status, $dsp_next)) {
                return respondError(
                    $lang == 'en' ? 'Invalid status transition.' : 'الحاله ليست متاحه للانتقال لها من الحاله الحاليه.',
                    400
                );
            }
            $this->dspService->updateStatus($dsp, $request->dsp_status);

            $dsp->refresh();
            return ResponseWithSuccessData(
                $lang,
                new DspResource($dsp),
                1
            );
        } catch (ModelNotFoundException $e) {
            return respondError(
                $lang == 'en' ? 'Purchase order not found.' : 'أمر الشراء غير موجود.',
                404
            );
        } catch (Exception $e) {
            return respondError(
                $lang == 'en' ? 'An error occurred while updating DSP status.' : 'حدث خطأ أثناء تحديث حالة أمر الشراء.',
                500
            );
        }
    }

    public function update(Request $request, $id)
    {
        $lang = $request->header('lang', 'ar');
        App::setLocale($lang);
        $employee = auth('employee')->user();

        $dsp = DirectSupplyPermission::findOrFail($id);
        $validator = Validator::make($request->all(), [
            'items' => 'required|array|min:1',
            'items.*.id' => 'required|exists:direct_supply_permission_items,id',
            'items.*.received_quantity' => 'required|numeric|min:0.01',
            'items.*.notes' => 'nullable|string',
            'items.*.has_added' => 'nullable|in:0,1',
            'items.*.has_issued' => 'nullable|in:0,1',
            'items.*.issues' => 'required_if:items.*.has_issued,1|array|min:1',
            'items.*.issues.*.issue_type_id' => 'required|exists:direct_supply_issue_types,id',
            'items.*.issues.*.unit_id' => 'nullable|exists:units,id',
            'items.*.issues.*.quantity' => 'required|numeric|min:0.01',
        ]);
        $validator->after(function ($validator) use ($request) {
            if ($request->has('items')) {
                foreach ($request->items as $index => $item) {
                    if (
                        isset($item['has_issued']) &&
                        $item['has_issued'] == 1 &&
                        (!isset($item['has_added']) || $item['has_added'] != 0)
                    ) {
                        $validator->errors()->add(
                            "items.$index.has_added",
                            "The has_added field must be 0 as there is an issue in item $index."
                        );
                    }
                }
            }
        });
        if ($validator->fails()) {
            return respondError(
                $lang == 'en' ? 'Validation Error.' : 'خطأ في التحقق.',
                400,
                $validator->errors()
            );
        }
        $items = $request->items;

        $totalQuantity = 0;
        $totalReceived = 0;
        $allIssued = true;
        $allNoIssue = true;
        $anyIssued = false;
        $allAdded = true;
        $allNotAdded = true;

        foreach ($items as $item) {
            $totalQuantity += $item['received_quantity'];
            $totalReceived += $item['received_quantity'];

            if (($item['has_issued'] ?? 0) == 1) {
                $anyIssued = true;
                $allNoIssue = false;
            } else {
                $allIssued = false;
            }

            if (($item['has_added'] ?? 0) == 1) {
                $allNotAdded = false;
            } else {
                $allAdded = false;
            }
        }
        $status = null;
        // Compare total quantities and determine status
        if ($totalQuantity === $totalReceived) {

            if ($allNoIssue && $allNotAdded) {
                $status = 3; // all quantities equal, all not added, no issues
            } elseif ($allNoIssue && $allAdded) {
                $status = 9; // all quantities equal, all added, no issues
            } elseif ($anyIssued && !$allIssued) {
                $status = 6; // some items have issue, some not
            } elseif ($allIssued) {
                $status = 8; // all items have issue
            }
        }
        $request->merge(['status' => $status]);
        $request->merge(['lang' => $lang]);

        $updated = $this->dspService->updateDSP($dsp, $request->all());
        $updated->load(['items', 'creator', 'qaTester']);
        $data = new DspResource($updated);

        return ResponseWithSuccessData($lang, $data, 1);
    }
