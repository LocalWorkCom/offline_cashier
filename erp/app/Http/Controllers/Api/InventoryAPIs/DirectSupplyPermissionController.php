    public function index(Request $request)
    {
        //list all dsp as manager or superadmin else only assigned qa_tester_id
        $lang = $request->header('lang', 'ar');
        App::setLocale($lang);
        $user = auth('employee')->user();
        if ($user->hasRole('Inventory_Manager', 'employee') || $user->hasRole('superAdmin', 'employee')) {
            $query = DirectSupplyPermission::query()->whereNull('deleted_at');
        } else {
            $query = DirectSupplyPermission::query()
                ->whereNull('deleted_at')
                ->where('qa_tester_id', $user->id);
        }

        //Optional filter
        if ($request->has('status_id')) {
            $query->where('dsp_status_id', $request->status_id);
        }

        //Include relationships before executing query
        $query->with([
            'items',
            'items.item.product',
            'qaTester',
            'fromStore',
            'toStore',
            'purchaseRequest',
            'items.item.productStores',
            'supplyOrder'
        ]);
        $dsps = paginateOrGetAll($query, $request, [], []);

        $data = DspResource::collection($dsps['data']);

        return ResponseWithSuccessDataPaginated($lang, [
            'data' => $data,
            'meta' => $dsps['meta'] ?? null,
        ], 1);
    }
