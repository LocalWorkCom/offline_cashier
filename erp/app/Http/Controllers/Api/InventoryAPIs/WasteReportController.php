    public function changeStatus(Request $request, $id)
    {
        $lang = $request->header('lang', 'ar');
        App::setLocale($lang);

        $employee = auth('employee')->user();

        $validator = Validator::make($request->all(), [
            'status' => 'required|in:pending,Being Audited,rejected,confirmed',
        ]);

        if ($validator->fails()) {
            return respondError(
                $lang == 'en' ? 'Validation Error.' : 'خطأ في التحقق.',
                400,
                $validator->errors()
            );
        }

        $wasteReport = WasteReport::find($id);

        if (!$wasteReport) {
            return respondError(
                $lang == 'en' ? 'Waste report not found.' : 'تقرير الهدر غير موجود.',
                404
            );
        }

        $currentStatus = $wasteReport->status;
        $newStatus = $request->status;
        if ($currentStatus === 'rejected') {
            return respondError(
                $lang == 'en'
                    ? 'A rejected report cannot change status.'
                    : 'لا يمكن تغيير حالة التقرير المرفوض.',
                403
            );
        }
        // Rule 1: If current status is pending → cannot change directly to confirmed
        if ($currentStatus === 'pending' && $newStatus === 'confirmed') {
            return respondError(
                $lang == 'en'
                    ? 'You cannot change directly from pending to confirmed.'
                    : 'لا يمكن التغيير مباشرةً من حالة معلق إلى تم الموافقة.',
                403
            );
        }

        // Rule 2: If current status is not pending → cannot change back to pending
        if ($currentStatus !== 'pending' && $newStatus === 'pending') {
            return respondError(
                $lang == 'en'
                    ? 'You cannot change back to pending once it has progressed.'
                    : 'لا يمكن العودة إلى حالة معلق بعد تغييرها.',
                403
            );
        }

        //Cannot confirm unless all items reviewed
        if ($newStatus === 'confirmed') {
            $unreviewedItemsCount = WasteReportItem::where('waste_report_id', $wasteReport->id)
                ->where('status', '!=', 'reviewed')
                ->count();

            if ($unreviewedItemsCount > 0) {
                return respondError(
                    $lang == 'en'
                        ? 'Cannot confirm this waste report until all items are reviewed.'
                        : 'لا يمكن تأكيد تقرير الإعدام قبل مراجعة جميع العناصر.',
                    403
                );
            }
        }

        $wasteReport->status = $newStatus;
        $wasteReport->updated_by = $employee->id;
        $wasteReport->save();
        if ($newStatus === 'rejected') {
            $items = WasteReportItem::where('waste_report_id', $wasteReport->id)->get();

            foreach ($items as $waste_item) {
                $waste_item->status = 'reviewed';
                $waste_item->updated_by = $employee->id;
                $waste_item->reviewed_employee_id = $employee->id;
                $waste_item->actual_quantity_wasted = 0;
                $waste_item->save();
            }
        }

        return ResponseWithSuccessData(
            $lang,
            null,
            1
        );
    }

    public function review(Request $request, $id)
    {
        $lang = $request->header('lang', 'ar');
        App::setLocale($lang);
        $employee = auth('employee')->user();

        $validator = Validator::make($request->all(), [
            'items' => 'required|array|min:1',
            'items.*.id' => 'required|exists:waste_report_items,id',
            'items.*.actual_quantity_wasted' => 'required|numeric|min:0',
            'items.*.waste_unit_id' => 'required|exists:units,id',
        ]);

        if ($validator->fails()) {
            return respondError(
                $lang == 'en' ? 'Validation Error.' : 'خطأ في التحقق.',
                400,
                $validator->errors()
            );
        }

        $wasteReport = WasteReport::find($id);

        if (!$wasteReport) {
            return respondError(
                $lang == 'en' ? 'Waste report not found.' : 'تقرير الإعدام غير موجود.',
                404
            );
        }

        $itemIds = collect($request->items)->pluck('id');
        $invalidItems = WasteReportItem::whereIn('id', $itemIds)
            ->where('waste_report_id', '!=', $wasteReport->id)
            ->pluck('id');

        if ($invalidItems->isNotEmpty()) {
            return respondError(
                $lang == 'en'
                    ? 'Some items do not belong to this waste report.'
                    : 'بعض العناصر لا تنتمي إلى تقرير الإعدام المحدد.',
                403
            );
        }

        // Block editing if rejected or confirmed
        if (in_array($wasteReport->status, ['rejected', 'confirmed'])) {
            return respondError(
                $lang == 'en'
                    ? 'This waste report has already been reviewed.'
                    : 'تمت مراجعة تقرير الإعدام من قبل.',
                400
            );
        }

        // Allow only if status is pending or Being Audited
        if (!in_array($wasteReport->status, ['Being Audited', 'pending'])) {
            return respondError(
                $lang == 'en'
                    ? 'You can only review items when the waste report is Being Audited or pending.'
                    : 'يمكنك مراجعة العناصر فقط عندما تكون حالة تقرير الإعدام "قيد المراجعة" أو "معلق".',
                400
            );
        }

        $updatedItems = [];

        foreach ($request->items as $itemData) {
            $item = WasteReportItem::where('id', $itemData['id'])
                ->where('waste_report_id', $wasteReport->id)
                ->first();

            if (!$item) continue;

            $item->actual_quantity_wasted = $itemData['actual_quantity_wasted'];
            $item->waste_unit_id = $itemData['waste_unit_id'];
            $item->status = 'reviewed';
            $item->reviewed_employee_id = $employee->id;
            $item->updated_by = $employee->id;
            $item->save();

            // Create Product Transaction (type = 'out')
            storeProductTransaction(
                $item->product_brand_id,
                $item->actual_quantity_wasted,
                $item->waste_unit_id,
                $item->barcode ?? null,
                $item->production_date ?? null,
                $item->expiration_date ?? null,
                'out',
                $employee,
                'waste_report_items',
                $item->id
            );

            $updatedItems[] = $item->id;
        }

        //Update waste report status based on item review progress
        $totalItems = WasteReportItem::where('waste_report_id', $wasteReport->id)->count();
        $reviewedItems = WasteReportItem::where('waste_report_id', $wasteReport->id)
            ->where('status', 'reviewed')
            ->count();

        $wasteReport->status = ($totalItems > 0 && $totalItems == $reviewedItems)
            ? 'confirmed'
            : 'Being Audited';
        $wasteReport->save();

        return ResponseWithSuccessData(
            $lang,
            $lang == 'en'
                ? 'Items reviewed successfully and waste report status updated.'
                : 'تمت مراجعة العناصر بنجاح وتحديث حالة تقرير الإعدام.',
            1
        );
    }

