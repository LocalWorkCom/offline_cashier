    public function store(Request $request)
    {
        $lang = $request->header('lang', 'ar');
        App::setLocale($lang);
        $employee = auth('employee')->user();

        $validator = Validator::make($request->all(), [
            'date' => [
                'nullable',
                'date_format:Y-m-d',
                'after_or_equal:' . now()->format('Y-m-d'),
            ],
            'time' => ['nullable', 'date_format:H:i:s'],
            'name' => 'required|string',
            'report_number' => 'nullable|string',
            'store_id' => 'required|exists:stores,id',
            'employee_id' => [
                'required',
                Rule::exists('employees', 'id')->where('flag', 'inventory'),
            ],
            //pending as will use in version 2
            // 'first_employee_id' => [
            //     'nullable',
            //     Rule::exists('employees', 'id')->where('flag', 'inventory'),
            // ],
            // 'second_employee_id' => [
            //     'nullable',
            //     Rule::exists('employees', 'id')->where('flag', 'inventory'),
            // ],
            'items' => 'required|array|min:1',
            'items.*.item_id' => 'required|exists:product_brands,id',
            'items.*.barcode' => [
                'required',
                Rule::exists('product_transactions', 'barcode')
                    ->where(function ($query) use ($request) {
                        // match barcode rows with the same product_brand_id
                        foreach ($request->items as $index => $item) {
                            $query->orWhere(function ($q) use ($item) {
                                $q->where('barcode', $item['barcode'])
                                    ->where('product_brand_id', $item['item_id']);
                            });
                        }
                    }),
            ],
            'items.*.unit_id' => 'required|exists:units,id',
            'items.*.quantity' => 'required|numeric|min:0.01',
            'items.*.reason_waste' => 'required|integer|exists:waste_reasons,id',
            'items.*.image' => 'required|file',
        ]);
        $validator->after(function ($validator) use ($request) {
            foreach ($request->items as $index => $item) {
                $barcode = $item['barcode'] ?? null;
                $productId = $item['item_id'] ?? null;
                $quantityRequested = $item['quantity'];

                // Get available stock
                $quantityData = getProductQuantity($productId, 'base', $barcode, null);
                $availableQuantity = $quantityData ?? 0;

                if ($quantityRequested > $availableQuantity) {
                    $message = __('validation.custom.items_quantity_exceeds_stock', [
                        'requested' => $quantityRequested,
                        'available' => $availableQuantity,
                    ]);

                    $validator->errors()->add("items.$index.quantity", $message);
                }
            }
        });

        if ($validator->fails()) {
            return respondError(
                $lang == 'en' ? 'Validation Error.' : 'خطأ في التحقق.',
                400,
                $validator->errors()
            );
        }

        // Permission check for manual report number update
        $canUpdateNumber = $employee && $employee->can('update wastreportnumber');

        // Always generate a new auto number
        do {
            $nextId = WasteReport::max('id') + 1;
            $report_number = 'WR-' . now()->format('Ymd') . '-' . str_pad($nextId, 4, '0', STR_PAD_LEFT);
        } while (WasteReport::where('report_number', $report_number)->exists());

        // If the user does NOT have permission, override any manual input
        if (!$canUpdateNumber) {
            $request->merge(['report_number' => $report_number]);
        } else {
            // If user provided a custom number, check uniqueness
            if ($request->filled('report_number') && WasteReport::where('report_number', $request->report_number)->exists()) {
                return respondError(
                    $lang == 'en' ? 'Report number already exists.' : 'رقم التقرير موجود بالفعل.',
                    400
                );
            }

            // If user didn’t provide a number, use auto one
            $request->merge(['report_number' => $request->report_number ?? $report_number]);
        }

        $wasteReport = new WasteReport();
        $wasteReport->store_id = $request->store_id;
        $wasteReport->name = $request->name;
        $wasteReport->date = $request->date;
        $wasteReport->time = $request->time;
        $wasteReport->report_number = $request->report_number;
        //pending as will use in version 2

        // $wasteReport->first_quality_officer_id = $request->first_employee_id;
        // $wasteReport->second_quality_officer_id = $request->second_employee_id;
        $wasteReport->employee_id = $request->employee_id;
        $wasteReport->created_by = $employee->id;
        $wasteReport->save();

        foreach ($request->items as $index => $item) {
            $waste_item = new WasteReportItem();
            $waste_item->waste_report_id = $wasteReport->id;
            $waste_item->barcode = $item['barcode'];
            $waste_item->product_brand_id = $item['item_id'];
            $waste_item->unit_id = $item['unit_id'];
            $waste_item->waste_reason_id = $item['reason_waste'];
            $waste_item->quantity = $item['quantity'];
            $waste_item->status = 'pending';
            $waste_item->created_by = $employee->id;
            $waste_item->save();

            if ($request->hasFile("items.$index.image")) {
                $file = $request->file("items.$index.image");
                UploadFile('images/wasteReports', 'image', $waste_item, $file);
            }
        }

        return ResponseWithSuccessData(
            $lang,
            $lang == 'en'
                ? "Waste report added successfully with number: {$wasteReport->report_number}."
                : "تم إضافة تقرير الإعدام بنجاح برقم: {$wasteReport->report_number}.",
            1
        );
    }

